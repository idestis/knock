// Rasterises knock-mark.svg into the pixel grid used by the CLI help banner.
// Run from the repo root: swift cli/internal/ui/gen/mark.swift > cli/internal/ui/mark_grid.go
import AppKit

let W = 30
let svg = NSImage(contentsOfFile: "design/logo/knock-mark.svg")!
let H = Int((Double(W) * svg.size.height / svg.size.width).rounded()) / 2 * 2 // even: two pixels per text row
let scale = 8
let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: W * scale, pixelsHigh: H * scale, bitsPerSample: 8,
                           samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
NSGraphicsContext.saveGraphicsState()
NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
svg.draw(in: NSRect(x: 0, y: 0, width: W * scale, height: H * scale))
NSGraphicsContext.restoreGraphicsState()

var rows: [String] = []
for y in 0..<H {
    var row = ""
    for x in 0..<W {
        // a pixel is on when at least ~45% of its supersampled area is covered
        var covered = 0
        for sy in 0..<scale { for sx in 0..<scale {
            if (rep.colorAt(x: x * scale + sx, y: y * scale + sy)?.alphaComponent ?? 0) > 0.5 { covered += 1 }
        } }
        row += covered * 100 / (scale * scale) >= 45 ? "#" : "."
    }
    rows.append(row)
}
print("// Code generated by gen/mark.swift from design/logo/knock-mark.svg; DO NOT EDIT.\n")
print("package ui\n")
print("// markGrid is the K mark, one string per pixel row; '#' is ink.")
print("var markGrid = []string{")
for r in rows { print("\t\"\(r)\",") }
print("}")
